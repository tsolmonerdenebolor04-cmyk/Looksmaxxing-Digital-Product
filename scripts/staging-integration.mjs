// Opt-in, synthetic staging fixtures only. This is NOT a Byl/QPay settlement test.
// Requires a separately approved Byl schema migration; never applies schema itself.
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { createStore } from '../lib/store.mjs';
import { saveReport } from '../lib/paywall.mjs';
import { createHandler as recoverHandler } from '../api/recover.mjs';
import { createHandler as reportHandler } from '../api/report.mjs';
import { createHandler as paymentHandler } from '../api/payment.mjs';
import { report } from '../tests/fixtures.mjs';
import { publicPreview } from '../lib/report.mjs';
import { stagingConfig, stagingOrigin } from './staging-config.mjs';

const config = stagingConfig(process.env);
const reportIds = [];
const checks = [];
const syntheticInvoice = String(Date.now());
function pass(name) { checks.push(name); console.log(`PASS ${name}`); }
async function guardedFetch(url, options = {}) {
  const target = new URL(url);
  assert.ok(target.origin === stagingOrigin && /^\/rest\/v1\/(reports|payments|events|byl_orders|byl_events|rpc\/(reserve_byl_invoice|bind_byl_invoice|settle_byl_invoice|has_verified_byl_payment|read_byl_report))$/.test(target.pathname), 'Disallowed integration target');
  return fetch(target, { ...options, redirect: 'error', signal: AbortSignal.timeout(10000) });
}
async function rest(table, query, method = 'GET', body, key = config.SUPABASE_SECRET_KEY) {
  const response = await guardedFetch(`${stagingOrigin}/rest/v1/${table}?${new URLSearchParams(query)}`, {
    method, headers: { apikey: key, ...(key.startsWith('sb_') ? {} : { Authorization: `Bearer ${key}` }),
      'Content-Type': 'application/json', Prefer: 'return=representation' },
    ...(body === undefined ? {} : { body: JSON.stringify(body) })
  });
  if (!response.ok) throw new Error(`Staging REST request failed (${response.status})`);
  return response.status === 204 ? null : response.json();
}
function response() {
  return { headers: {}, statusCode: 200, setHeader(k,v) { this.headers[k]=v; },
    status(n) { this.statusCode=n;return this; }, json(body) { this.body=body; } };
}
const store = createStore(config, guardedFetch);
// Record only IDs generated by this run, including before uncertain insert outcomes.
const ownedStore = { ...store, insertReport(row) { reportIds.push(row.id); return store.insertReport(row); } };
async function invoke(factory, id, cookie, method = 'GET', body) {
  const res = response();
  await factory(() => store)({ method, url:`/api/test?id=${id}`, headers:cookie ? {cookie} : {}, body }, res);
  const serialized = JSON.stringify(res);
  assert.ok(!serialized.includes(config.SUPABASE_SECRET_KEY) && !serialized.includes(config.publishableKey), 'Server credentials must not be returned');
  return res;
}
try {
  await store.health();
  await rest('byl_orders',{select:'report_id',limit:'0'});
  await rest('byl_events',{select:'event_id',limit:'0'});
  assert.equal(await store.hasVerifiedPayment(randomUUID()),false);
  pass('real Supabase and approved Byl schema read preflight');
  const res = response();
  const saved = await saveReport(ownedStore, { ...report, headline:'SYNTHETIC STAGING INTEGRATION — NO CUSTOMER DATA' }, res, {NODE_ENV:'production'});
  const id = saved.reportId, cookie = res.headers['Set-Cookie'].split(';')[0];
  const rows = await rest('reports', {select:'id,report,status,access_token_hash',id:`eq.${id}`});
  assert.ok(rows.length===1 && rows[0].status==='unpaid' && !!rows[0].report);
  assert.ok(!JSON.stringify(saved).includes(report.barberCard));
  pass('real report insert/select and preview-only creation');

  let result = await invoke(recoverHandler,id,cookie);
  assert.ok(result.statusCode===200 && result.body.paid===false && result.body.report===undefined);
  assert.deepEqual(result.body.preview,saved.preview);
  assert.deepEqual(result.body.preview,publicPreview(rows[0].report));
  assert.ok(result.body.preview.observations.length===3 && !!result.body.preview.priority.action);
  for (const key of ['haircuts','barberCard','skin','grooming','wardrobe','photoTips','budget','avoidSpending','weeks','limitations','priorities','roasts']) {
    assert.ok(!(key in result.body.preview));
  }
  assert.ok((await invoke(reportHandler,id,cookie)).statusCode===402);
  pass('unpaid cookie-authorized recovery stays locked');
  for (const auth of [undefined,cookie.replace(/=.+$/, '='+'x'.repeat(43))]) {
    assert.ok((await invoke(recoverHandler,id,auth)).statusCode===404);
    assert.ok((await invoke(reportHandler,id,auth)).statusCode===404);
  }
  pass('missing/forged cookie authentication denied');

  // Browser-role direct API access must neither read private rows nor change payment status.
  for (const method of ['GET','PATCH']) {
    const anon = await guardedFetch(`${stagingOrigin}/rest/v1/reports?id=eq.${id}&select=id`, {
      method, headers:{apikey:config.publishableKey,'Content-Type':'application/json',Prefer:'return=representation'},
      ...(method==='PATCH' ? {body:JSON.stringify({status:'paid'})} : {})
    });
    assert.ok([200,401,403].includes(anon.status));
    if (anon.status===200) assert.ok((await anon.json()).length===0);
  }
  assert.ok((await rest('reports',{select:'status',id:`eq.${id}`}))[0].status==='unpaid');
  pass('publishable-key direct reads and status tampering blocked by RLS/grants');

  result = await invoke(paymentHandler,id,cookie,'POST',{reportId:id,status:'paid'});
  assert.ok(result.statusCode===503);
  pass('checkout remains disabled against real storage');

  // Deliberately synthetic authorization fixture; never a real provider confirmation.
  await rest('reports',{id:`eq.${id}`},'PATCH',{status:'paid',paid_at:new Date().toISOString()});
  assert.ok((await invoke(reportHandler,id,cookie)).statusCode===402);
  await rest('reports',{id:`eq.${id}`},'PATCH',{status:'unpaid',paid_at:null});
  await store.reserveByl(id,rows[0].access_token_hash,1);
  await store.bindByl(id,syntheticInvoice,1,`https://byl.mn/h/invoice/${syntheticInvoice}/SyntheticFixture`);
  await store.settleByl({reportId:id,invoiceId:syntheticInvoice,projectId:1,amount:6900,status:'paid',eventId:'synthetic-'+id});
  result = await invoke(recoverHandler,id,cookie);
  assert.ok(result.body.paid===true && result.body.report===undefined);
  result = await invoke(reportHandler,id,cookie);
  assert.ok(result.statusCode===200 && result.body.report.barberCard===report.barberCard);
  pass('synthetic paid authorization fixture permits owner retrieval only');
  await store.settleByl({reportId:id,invoiceId:syntheticInvoice,projectId:1,amount:6900,status:'void',eventId:'synthetic-void-'+id});
  assert.ok((await invoke(reportHandler,id,cookie)).statusCode===402);
  pass('refunded fixture revokes paid retrieval');
  await rest('reports',{id:`eq.${id}`},'PATCH',{expires_at:'2000-01-01T00:00:00Z'});
  assert.ok((await invoke(recoverHandler,id,cookie)).statusCode===404);
  assert.ok((await invoke(reportHandler,id,cookie)).statusCode===404);
  pass('expired report cannot recover preview or full content');
} finally {
  // Exact per-run IDs only; never truncate tables, alter schema, or touch unrelated rows.
  const failedCleanup = [];
  for (const id of reportIds) {
    try {
      await rest('events',{report_id:`eq.${id}`},'DELETE');
      await rest('byl_events',{report_id:`eq.${id}`},'DELETE');
      await rest('byl_orders',{report_id:`eq.${id}`},'DELETE');
      await rest('payments',{report_id:`eq.${id}`},'DELETE');
      await rest('reports',{id:`eq.${id}`},'DELETE');
    } catch { failedCleanup.push(id); }
  }
  if (failedCleanup.length) throw new Error(`Manual staging fixture cleanup required for report IDs: ${failedCleanup.join(', ')}`);
  if (reportIds.length) pass('per-run fixture cleanup');
}
console.log(`Staging integration complete: ${checks.length} checks. No Gemini, Byl or QPay requests.`);
